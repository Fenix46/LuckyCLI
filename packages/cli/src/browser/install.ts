/**
 * Install the Lucky browser native messaging host.
 *
 * Chrome will only start a native host registered in its own
 * `NativeMessagingHosts` directory, with an `allowed_origins` list that matches
 * the extension. This module writes the wrapper, the manifest for every
 * detected Chromium-family browser, and the status/uninstall commands.
 *
 * The extension ID is fixed by the `key` in the extension manifest, so the
 * allowed origin is stable across machines and reloads.
 */
import { chmod, mkdir, rm, stat, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { browserBridgeDir, listBrowserBridgeSockets } from "@luckycli/core";

export const NATIVE_HOST_NAME = "com.luckycli.browser_extension";
export const EXTENSION_ID = "lcliakcldefkkiegbfchoifkconomego";
export const WRAPPER_NAME = "chrome-native-host";

export interface BrowserTarget {
  id: string;
  name: string;
  /** NativeMessagingHosts directory. */
  dir: string;
  /** Files that prove the browser is installed. */
  markers: string[];
}

export interface InstallOptions {
  home?: string;
  platform?: NodeJS.Platform;
  /** Existence probe, injectable for tests. */
  exists?: (path: string) => Promise<boolean>;
  /** Executable that should run `browser host` (defaults to this process). */
  execPath?: string;
  /** Script entry when running from source (defaults to argv[1]). */
  entryPath?: string;
}

export interface InstalledHost {
  browser: string;
  manifest: string;
}

export interface BrowserStatus {
  target: BrowserTarget;
  installed: boolean;
  manifestPresent: boolean;
  wrapperPresent: boolean;
}

export function wrapperPath(home = homedir()): string {
  return join(home, ".luckycli", WRAPPER_NAME);
}

/** Chromium-family browsers and their macOS/Linux manifest directories. */
export function browserTargets(
  platform: NodeJS.Platform = process.platform,
  home = homedir(),
): BrowserTarget[] {
  if (platform === "darwin") {
    return [
      target("chrome", "Google Chrome", join(home, "Library", "Application Support", "Google", "Chrome", "NativeMessagingHosts"), ["/Applications/Google Chrome.app"]),
      target("brave", "Brave", join(home, "Library", "Application Support", "BraveSoftware", "Brave-Browser", "NativeMessagingHosts"), ["/Applications/Brave Browser.app"]),
      target("arc", "Arc", join(home, "Library", "Application Support", "Arc", "User Data", "NativeMessagingHosts"), ["/Applications/Arc.app"]),
      target("edge", "Microsoft Edge", join(home, "Library", "Application Support", "Microsoft Edge", "NativeMessagingHosts"), ["/Applications/Microsoft Edge.app"]),
      target("chromium", "Chromium", join(home, "Library", "Application Support", "Chromium", "NativeMessagingHosts"), ["/Applications/Chromium.app"]),
      target("vivaldi", "Vivaldi", join(home, "Library", "Application Support", "Vivaldi", "NativeMessagingHosts"), ["/Applications/Vivaldi.app"]),
      target("opera", "Opera", join(home, "Library", "Application Support", "com.operasoftware.Opera", "NativeMessagingHosts"), ["/Applications/Opera.app"]),
    ];
  }
  return [
    target("chrome", "Google Chrome", join(home, ".config", "google-chrome", "NativeMessagingHosts"), ["/usr/bin/google-chrome", "/usr/bin/google-chrome-stable"]),
    target("brave", "Brave", join(home, ".config", "BraveSoftware", "Brave-Browser", "NativeMessagingHosts"), ["/usr/bin/brave-browser", "/usr/bin/brave"]),
    target("chromium", "Chromium", join(home, ".config", "chromium", "NativeMessagingHosts"), ["/usr/bin/chromium", "/usr/bin/chromium-browser"]),
    target("edge", "Microsoft Edge", join(home, ".config", "microsoft-edge", "NativeMessagingHosts"), ["/usr/bin/microsoft-edge", "/usr/bin/microsoft-edge-stable"]),
    target("vivaldi", "Vivaldi", join(home, ".config", "vivaldi", "NativeMessagingHosts"), ["/usr/bin/vivaldi", "/usr/bin/vivaldi-stable"]),
    target("opera", "Opera", join(home, ".config", "opera", "NativeMessagingHosts"), ["/usr/bin/opera"]),
  ];
}

function target(id: string, name: string, dir: string, markers: string[]): BrowserTarget {
  return { id, name, dir, markers };
}

/** The shell wrapper Chrome will execute. */
export function wrapperScript(execPath: string, entryPath?: string): string {
  const entry = entryPath && entryPath !== execPath ? ` "${resolve(entryPath)}"` : "";
  return `#!/bin/sh\n# Generated by LuckyCLI - do not edit manually\nexec "${resolve(execPath)}"${entry} browser host\n`;
}

/** The manifest Chrome reads for `NATIVE_HOST_NAME`. */
export function hostManifest(wrapper = wrapperPath()): string {
  return `${JSON.stringify(
    {
      name: NATIVE_HOST_NAME,
      description: "Lucky browser bridge native host",
      path: wrapper,
      type: "stdio",
      allowed_origins: [`chrome-extension://${EXTENSION_ID}/`],
    },
    null,
    2,
  )}\n`;
}

async function defaultExists(path: string): Promise<boolean> {
  return Boolean(await stat(path).catch(() => null));
}

async function anyExists(
  paths: string[],
  exists: (path: string) => Promise<boolean>,
): Promise<boolean> {
  for (const path of paths) {
    if (await exists(path)) return true;
  }
  return false;
}

/** Install the wrapper and a manifest for each detected browser. */
export async function installNativeHost(
  options: InstallOptions = {},
): Promise<InstalledHost[]> {
  const home = options.home ?? homedir();
  const platform = options.platform ?? process.platform;
  if (platform === "win32") {
    throw new Error("Windows native host installation is not implemented yet (use WSL or macOS/Linux).");
  }
  const exists = options.exists ?? defaultExists;
  const execPath = options.execPath ?? process.execPath;
  // A compiled Lucky binary is launched directly; Node (dev) needs the script
  // entry between the executable and the subcommand.
  const isNode = /(^|[\\/])node(\.exe)?$/i.test(execPath);
  const entryPath = options.entryPath ?? (isNode ? process.argv[1] : undefined);

  const wrapper = wrapperPath(home);
  await mkdir(dirname(wrapper), { recursive: true, mode: 0o700 });
  await chmod(dirname(wrapper), 0o700).catch(() => {});
  await writeFile(wrapper, wrapperScript(execPath, entryPath), { mode: 0o700 });
  await chmod(wrapper, 0o700).catch(() => {});

  const installed: InstalledHost[] = [];
  for (const target of browserTargets(platform, home)) {
    if (!(await anyExists(target.markers, exists))) continue;
    const manifest = join(target.dir, `${NATIVE_HOST_NAME}.json`);
    await mkdir(target.dir, { recursive: true });
    await writeFile(manifest, hostManifest(wrapper), "utf8");
    installed.push({ browser: target.name, manifest });
  }
  return installed;
}

/** Status of every supported browser plus the live bridge sockets. */
export async function browserStatus(
  options: InstallOptions = {},
): Promise<{ hosts: BrowserStatus[]; sockets: string[]; wrapper: string; wrapperPresent: boolean }> {
  const home = options.home ?? homedir();
  const platform = options.platform ?? process.platform;
  const exists = options.exists ?? defaultExists;
  const wrapper = wrapperPath(home);
  const wrapperPresent = await exists(wrapper);
  const hosts: BrowserStatus[] = [];
  for (const target of browserTargets(platform, home)) {
    const manifestPresent = await exists(join(target.dir, `${NATIVE_HOST_NAME}.json`));
    hosts.push({
      target,
      installed: manifestPresent || (await anyExists(target.markers, exists)),
      manifestPresent,
      wrapperPresent,
    });
  }
  return {
    hosts,
    sockets: listBrowserBridgeSockets({ dir: browserBridgeDir() }),
    wrapper,
    wrapperPresent,
  };
}

/** Remove the manifests this installer wrote and the wrapper. */
export async function uninstallNativeHost(options: InstallOptions = {}): Promise<string[]> {
  const home = options.home ?? homedir();
  const platform = options.platform ?? process.platform;
  const removed: string[] = [];
  for (const target of browserTargets(platform, home)) {
    const manifest = join(target.dir, `${NATIVE_HOST_NAME}.json`);
    try {
      await rm(manifest);
      removed.push(manifest);
    } catch {
      // not installed
    }
  }
  const wrapper = wrapperPath(home);
  try {
    await rm(wrapper);
    removed.push(wrapper);
  } catch {
    // not installed
  }
  return removed;
}
